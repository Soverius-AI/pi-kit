export function isAngularSource(file) {
  const path = file.replaceAll("\\", "/");
  return /\.(ts|html|css)$/.test(path) && !path.startsWith('libs/shared/api/src/generated/') && angularRoots.some((root) => path.startsWith(`${root}/src/`));
}
